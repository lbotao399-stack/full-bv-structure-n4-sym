"""Round-2 check: effect of the two rescaling-type scheme changes on the even components, at the level of
local functionals int omega f with f a scalar density of Weyl weight w (explicit position of weight -1).

Conventions used (and their sources):
  * {S^(1)(v), int omega f} = int omega rho0(v) f, rho0(v) f = v.grad f + (w/4) div(v) f  (ch07 def:c7-vdot,
    lem:c7-weights; sign confirmed by engine B part2.classical: {S^(1)(Delta),O} = 2(E+w_O)O).
  * The bracket of psl(4|4) on vector fields is [v,u] = v(u) - u(v) (ch02 def:c2-bracket); with it
    ch08 cor:c8-homotopy (ii) reads [ad_{S1(x1)}, ad_{S1(x2)}] = -ad_{S1([x1,x2])} for even x1, x2.
  * Composition of the operators ad_{S1(v)} on functionals reverses the order of the density operators:
    ad_u ad_v (int omega f) = int omega rho0(v) rho0(u) f.
  * A field redefinition generated by phi (F -> F + hbar s phi) conjugates L by 1 + hbar ad_phi
    (ch08 prop:c8-laws (a)); for phi = kappa S^(1)(Delta) this is the finite part psi' = kappa ad_{S1(Delta)}.
Checked: (1) the order-reversal identity reproduces cor:c8-homotopy (ii); (2) the change [ad_{S1(x)}, psi']
of the component along x for psi' = kappa ad_{S1(Delta)}, x in {P_b, K_b, so(V), Delta}; (3) ad_{S1(Delta)}
commutes with derivatives of the density (well defined on functionals int omega f); (4) 'c times the Weyl
weight of the density' does not (so it is not a map of local functionals).
"""
import json, os, itertools
import sympy as sp

x = sp.symbols('x0:4'); w = sp.Symbol('w'); kap, c = sp.symbols('kappa c')
mons = [m for d in range(4) for m in itertools.combinations_with_replacement(x, d)]
coef = sp.symbols('f0:%d' % len(mons))
f = sum(cf * sp.Mul(*m) for cf, m in zip(coef, mons))
b = [1, -2, 3, 1]

def vf(kind):
    if kind == 'P': return [sp.Integer(t) for t in b]
    if kind == 'K':
        xx = sum(t * t for t in x); bx = sum(bi * t for bi, t in zip(b, x))
        return [sp.expand(xx * bi - 2 * bx * t) for bi, t in zip(b, x)]
    if kind == 'M': return [x[1], -x[0], 0, 0]
    if kind == 'D': return [2 * t for t in x]
def div(v): return sp.expand(sum(sp.diff(v[i], x[i]) for i in range(4)))
def br(v, u): return [sp.expand(sum(v[j] * sp.diff(u[i], x[j]) - u[j] * sp.diff(v[i], x[j]) for j in range(4))) for i in range(4)]
# weight change of the density under the classical transformation along v (explicit position weight -1)
dweight = {'P': 1, 'K': -1, 'M': 0, 'D': 0}
def rho0(v, wt):
    return lambda g: sp.expand(sum(v[i] * sp.diff(g, x[i]) for i in range(4)) + wt / 4 * div(v) * g)
res = {}
# (1) [ad_u, ad_v] on int omega f  <->  rho0(v) rho0(u) - rho0(u) rho0(v)  (all at the weight w of the field f)
ok = True
for a, bb in itertools.combinations(['P', 'K', 'M', 'D'], 2):
    u, v = vf(a), vf(bb)
    lhs = sp.expand(rho0(v, w)(rho0(u, w)(f)) - rho0(u, w)(rho0(v, w)(f)))
    rhs = sp.expand(-rho0(br(u, v), w)(f))
    ok = ok and sp.expand(lhs - rhs) == 0
res['order_reversal_reproduces_cor_c8_homotopy_ii'] = ok
# (2) shift of the component along x under psi' = kappa ad_{S1(Delta)}:
#     [ad_x, psi'] (int omega f) <-> kappa (rho0(D) rho0(v) - rho0(v) rho0(D)) f
shifts = {}
for kind in ['P', 'K', 'M', 'D']:
    v = vf(kind); D = vf('D')
    t1 = sp.expand(kap * (rho0(D, w)(rho0(v, w)(f)) - rho0(v, w)(rho0(D, w)(f))))
    base = rho0(v, w)(f)
    m1 = sp.simplify(sp.cancel(t1 / base)) if base != 0 else sp.Integer(0)
    shifts[kind] = str(m1)
res['shift_under_kappa_adS1Delta_multiple_of_classical'] = shifts
# (3) ad_{S1(Delta)} is well defined on functionals: rho0^(w+1)(Delta) d_i f = d_i rho0^(w)(Delta) f
D = vf('D')
res['adS1Delta_commutes_with_derivatives'] = all(
    sp.expand(rho0(D, w + 1)(sp.diff(f, x[i])) - sp.diff(rho0(D, w)(f), x[i])) == 0 for i in range(4))
# (4) 'c times the Weyl weight of the density' does not commute with derivatives: int (d omega) f = - int omega (d f)
res['c_times_density_weight_commutes_with_derivatives'] = all(
    sp.expand(c * (w + 1) * sp.diff(f, x[i]) - sp.diff(c * w * f, x[i])) == 0 for i in range(4))
res['reading'] = ('phi = kappa S^(1)(Delta) (F -> F + hbar s phi, i.e. psi\' = kappa ad_{S1(Delta)}) changes the components '
                  'along P_b, K_b, so(V), Delta by -2 kappa hbar, +2 kappa hbar, 0, 0 times the classical transformation; '
                  'ad_{S1(Delta)} is a well-defined map of local functionals, while multiplication by c times the Weyl '
                  'weight of the density is not (it does not commute with integration by parts in omega).')
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'scheme_shift_round2.json')
json.dump(res, open(out, 'w'), indent=1)
print(json.dumps(res, indent=1))
