#!/usr/bin/env python3
"""Generate the round-2 drawing-only FeynArts classes model N4Draw2.mod
(generic model: N4Draw.gen, unchanged).  Round-1 files N4Draw.mod / vertex_origin.tsv are untouched.

Line species (all generic S):
  P(eps,infty) edges (classical_spec.md section 7), as in round 1:
    S[1]  A|_V,  S[2]  A|_{W^perp},  S[3]  lambda  (self-conjugate)
    S[4]  c -> A^*|_V  (oriented, arrow from the c end to the A^* end)
  K_eps edges (Delta_eps = -partial_{K_eps}), as in round 1, oriented field end -> antifield end:
    S[21] A|_V -> A^*|_V, S[22] A|_W -> A^*|_W, S[23] lambda -> lambda^*, S[24] c -> c^*
  special edge K_eps - K_0 of the QME defect (1/2)({I,I}_eps - {I,I}_0), oriented field end -> antifield end:
    S[51] A|_V -> A^*|_V, S[52] A|_W -> A^*|_W, S[53] lambda -> lambda^*, S[54] c -> c^*
  external-only antifield legs (never internal):
    S[41] A^*|_{W^perp},  S[42] lambda^*,  S[43] c^*
  (external c and A^*|_V legs use S[4], as in round 1)

Orientation: an oriented species flows from its field end to its antifield end; in a FeynArts
coupling the field end appears as -X and the antifield end as X.
Vertices: the cubic and quartic vertices of I (classical_spec.md section 8), slot by slot.
"""
import itertools, os

HERE = os.path.dirname(os.path.abspath(__file__))

SLOT = {
    'AV':   ['S[1]', '-S[21]', '-S[51]'],
    'AW':   ['S[2]', '-S[22]', '-S[52]'],
    'LAM':  ['S[3]', '-S[23]', '-S[53]'],
    'C':    ['-S[4]', '-S[24]', '-S[54]'],
    'ASV':  ['S[4]', 'S[21]', 'S[51]'],
    'ASW':  ['S[22]', 'S[52]', 'S[41]'],
    'LAMS': ['S[23]', 'S[53]', 'S[42]'],
    'CS':   ['S[24]', 'S[54]', 'S[43]'],
}

BASE = [
    ('V3VVV',  ['AV', 'AV', 'AV']),
    ('V3VWW',  ['AV', 'AW', 'AW']),
    ('V4VVVV', ['AV', 'AV', 'AV', 'AV']),
    ('V4VVWW', ['AV', 'AV', 'AW', 'AW']),
    ('V4WWWW', ['AW', 'AW', 'AW', 'AW']),
    ('YV',     ['LAM', 'LAM', 'AV']),
    ('YW',     ['LAM', 'LAM', 'AW']),
    ('GV',     ['AV', 'C', 'ASV']),
    ('GW',     ['AW', 'C', 'ASW']),
    ('CLL',    ['C', 'LAM', 'LAMS']),
    ('CCC',    ['C', 'C', 'CS']),
]


def key(f):
    s = f.lstrip('-')
    return (int(s[2:-1]), f.startswith('-'))


def main():
    coup, origin = {}, {}
    for name, slots in BASE:
        for combo in itertools.product(*[SLOT[s] for s in slots]):
            ms = tuple(sorted(combo, key=key))
            coup[ms] = '{{1}}'
            origin.setdefault(ms, set()).add(name)
    for ms, o in origin.items():
        if len(o) != 1:
            raise SystemExit('multiset from two base vertices: %s %s' % (ms, o))
    classes = [
        ('S[1]', True, r'A|_V', 'Sine', 'None'),
        ('S[2]', True, r'A|_{W^\\perp}', 'ScalarDash', 'None'),
        ('S[3]', True, r'\\lambda', 'Straight', 'None'),
        ('S[4]', False, r'c\\to A^*', 'GhostDash', 'Forward'),
        ('S[21]', False, r'K_\\varepsilon', '"BandSine "', 'Forward'),
        ('S[22]', False, r'K_\\varepsilon', '"BandScalarDash "', 'Forward'),
        ('S[23]', False, r'K_\\varepsilon', '"BandStraight "', 'Forward'),
        ('S[24]', False, r'K_\\varepsilon', '"BandGhostDash "', 'Forward'),
        ('S[41]', False, r'A^*|_{W^\\perp}', 'ScalarDash', 'Forward'),
        ('S[42]', False, r'\\lambda^*', 'Straight', 'Forward'),
        ('S[43]', False, r'c^*', 'GhostDash', 'Forward'),
        ('S[51]', False, r'K_\\varepsilon-K_0', '"BandSine "', 'Forward'),
        ('S[52]', False, r'K_\\varepsilon-K_0', '"BandScalarDash "', 'Forward'),
        ('S[53]', False, r'K_\\varepsilon-K_0', '"BandStraight "', 'Forward'),
        ('S[54]', False, r'K_\\varepsilon-K_0', '"BandGhostDash "', 'Forward'),
    ]
    out = ['(* N4Draw2.mod -- round-2 drawing-only classes model, generated by gen_model2.py; do not edit *)\n',
           'M$ClassesDescription = {']
    cl = []
    for f, sc, lab, typ, arr in classes:
        cl.append('  %s == {\n\tSelfConjugate -> %s,\n\tIndices -> {},\n\tMass -> 0,\n\tPropagatorLabel -> "%s",\n\tPropagatorType -> %s,\n\tPropagatorArrow -> %s }'
                  % (f, 'True' if sc else 'False', lab, typ, arr))
    out.append(',\n'.join(cl))
    out.append('}\n')
    out.append('M$CouplingMatrices = {')
    lines = ['  C[%s] == %s' % (', '.join(ms), coup[ms]) for ms in sorted(coup, key=lambda m: (len(m), [key(f) for f in m]))]
    out.append(',\n'.join(lines))
    out.append('}\n')
    out.append('M$LastModelRules = {}\n')
    with open(os.path.join(HERE, 'N4Draw2.mod'), 'w') as fh:
        fh.write('\n'.join(out))
    with open(os.path.join(HERE, 'vertex_origin2.tsv'), 'w') as fh:
        for ms in sorted(coup, key=lambda m: (len(m), [key(f) for f in m])):
            fh.write('%s\t%s\t%s\n' % (' '.join(ms), next(iter(origin[ms])), coup[ms]))
    print('classes:', len(classes), 'couplings:', len(coup))


if __name__ == '__main__':
    main()
