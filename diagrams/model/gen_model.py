#!/usr/bin/env python3
"""Generate the drawing-only FeynArts classes model N4Draw.mod.

Line species = FeynArts classes fields (all of generic type S):

  P(eps,infty) edges (classical_spec.md section 7):
    S[1]  A|_V          A|_V (x) A|_V         self-conjugate   Sine
    S[2]  A|_{W^perp}   A|_W (x) A|_W         self-conjugate   ScalarDash
    S[3]  lambda        lambda (x) lambda     self-conjugate   Straight
    S[4]  c -> A^*|_V   c (x) A^*|_V          oriented         GhostDash, arrow c -> A^*
  L_eps = (Q^GF (x) 1) K_eps edges (pinned at t = eps; eps d/d eps P = -eps L_eps):
    S[11..14]  same field content as S[1..4], band style
  K_eps edges (pinned at t = eps; Delta_eps = -partial_{K_eps}):
    S[21]  A|_V -> A^*|_V,  S[22]  A|_W -> A^*|_W,  S[23]  lambda -> lambda^*,
    S[24]  c -> c^*         (oriented, arrow towards the antifield end), band style
  sources (external only):
    S[31]  O   = (iota_{w1}A, iota_{w2}A) insertion          double line
    S[32]  Delta : S^{(1)}(Delta) cochain (dilatation ghost)  zigzag

Orientation: an oriented line species X flows from its field end to its
antifield end; in a FeynArts coupling the field end appears as -X and the
antifield end as X.

Vertices (classical_spec.md section 8, plus the O vertex and the S^{(1)}
vertex) are expanded slot by slot over the species that can end on the slot.
"""
import itertools, os

HERE = os.path.dirname(os.path.abspath(__file__))

# slot kind -> list of coupling-field strings
SLOT = {
    'AV':  ['S[1]', 'S[11]', '-S[21]'],
    'AW':  ['S[2]', 'S[12]', '-S[22]'],
    'LAM': ['S[3]', 'S[13]', '-S[23]'],
    'C':   ['-S[4]', '-S[14]', '-S[24]'],
    'ASV': ['S[4]', 'S[14]', 'S[21]'],
    'ASW': ['S[22]'],
    'LAMS': ['S[23]'],
    'CS':  ['S[24]'],
    'OSRC': ['S[31]'],
    'DSRC': ['S[32]'],
}

# name, slots, counterterm column (None = tree only)
BASE = [
    ('V3VVV',  ['AV', 'AV', 'AV'], None),
    ('V3VWW',  ['AV', 'AW', 'AW'], None),
    ('V4VVVV', ['AV', 'AV', 'AV', 'AV'], None),
    ('V4VVWW', ['AV', 'AV', 'AW', 'AW'], None),
    ('V4WWWW', ['AW', 'AW', 'AW', 'AW'], None),
    ('YV',     ['LAM', 'LAM', 'AV'], None),
    ('YW',     ['LAM', 'LAM', 'AW'], None),
    ('GV',     ['AV', 'C', 'ASV'], None),
    ('GW',     ['AW', 'C', 'ASW'], None),
    ('CLL',    ['C', 'LAM', 'LAMS'], None),
    ('CCC',    ['C', 'C', 'CS'], None),
    ('O',      ['OSRC', 'AW', 'AW'], 'tree+ct'),   # O vertex; its counterterm partial_delta I^CT carries the same legs
    ('OCTV',   ['OSRC', 'AV', 'AV'], 'ct'),        # counterterm-only (A|_V, A|_V) part of partial_delta I^CT
    ('DV',     ['DSRC', 'AV', 'ASV'], None),
    ('DW',     ['DSRC', 'AW', 'ASW'], None),
    ('DL',     ['DSRC', 'LAM', 'LAMS'], None),
    ('DC',     ['DSRC', 'C', 'CS'], None),
]


def key(f):
    s = f.lstrip('-')
    n = int(s[2:-1])
    return (n, f.startswith('-'))


def main():
    coup = {}
    origin = {}
    for name, slots, ct in BASE:
        for combo in itertools.product(*[SLOT[s] for s in slots]):
            ms = tuple(sorted(combo, key=key))
            val = {None: '{{1}}', 'tree+ct': '{{1, 1}}', 'ct': '{{0, 1}}'}[ct]
            if ms in coup and coup[ms] != val:
                raise SystemExit('conflicting coupling ' + str(ms))
            coup[ms] = val
            origin.setdefault(ms, set()).add(name)
    # every multiset must come from a single base vertex
    for ms, o in origin.items():
        if len(o) != 1:
            raise SystemExit('multiset from two base vertices: %s %s' % (ms, o))

    classes = [
        ('S[1]', True, r'A|_V', 'Sine', 'None'),
        ('S[2]', True, r'A|_{W^\\perp}', 'ScalarDash', 'None'),
        ('S[3]', True, r'\\lambda', 'Straight', 'None'),
        ('S[4]', False, r'c\\to A^*', 'GhostDash', 'Forward'),
        ('S[11]', True, r'L_\\varepsilon', '"BandSine "', 'None'),
        ('S[12]', True, r'L_\\varepsilon', '"BandScalarDash "', 'None'),
        ('S[13]', True, r'L_\\varepsilon', '"BandStraight "', 'None'),
        ('S[14]', False, r'L_\\varepsilon', '"BandGhostDash "', 'Forward'),
        ('S[21]', False, r'K_\\varepsilon', '"BandSine "', 'Forward'),
        ('S[22]', False, r'K_\\varepsilon', '"BandScalarDash "', 'Forward'),
        ('S[23]', False, r'K_\\varepsilon', '"BandStraight "', 'Forward'),
        ('S[24]', False, r'K_\\varepsilon', '"BandGhostDash "', 'Forward'),
        ('S[31]', True, r'O', '"DoubleLine "', 'None'),
        ('S[32]', True, r'\\Delta', '"Zigzag "', 'None'),
    ]
    out = []
    out.append('(* N4Draw.mod -- drawing-only classes model, generated by gen_model.py; do not edit *)\n')
    out.append('M$ClassesDescription = {')
    cl = []
    for f, sc, lab, typ, arr in classes:
        cl.append('  %s == {\n\tSelfConjugate -> %s,\n\tIndices -> {},\n\tMass -> 0,\n\tPropagatorLabel -> "%s",\n\tPropagatorType -> %s,\n\tPropagatorArrow -> %s }'
                  % (f, 'True' if sc else 'False', lab, typ, arr))
    out.append(',\n'.join(cl))
    out.append('}\n')
    out.append('M$CouplingMatrices = {')
    lines = []
    for ms in sorted(coup, key=lambda m: (len(m), [key(f) for f in m])):
        lines.append('  C[%s] == %s' % (', '.join(ms), coup[ms]))
    out.append(',\n'.join(lines))
    out.append('}\n')
    out.append('M$LastModelRules = {}\n')
    with open(os.path.join(HERE, 'N4Draw.mod'), 'w') as fh:
        fh.write('\n'.join(out))
    # vertex-origin table for the enumerator (multiset -> base vertex name)
    with open(os.path.join(HERE, 'vertex_origin.tsv'), 'w') as fh:
        for ms in sorted(coup, key=lambda m: (len(m), [key(f) for f in m])):
            fh.write('%s\t%s\t%s\n' % (' '.join(ms), next(iter(origin[ms])), coup[ms]))
    print('couplings:', len(coup))


if __name__ == '__main__':
    main()
