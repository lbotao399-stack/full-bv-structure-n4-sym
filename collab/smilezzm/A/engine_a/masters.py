"""Engine A, module 1: exact one-loop Schwinger integrals with the heat-kernel cutoff.

Every edge carries e^{-eps |k|^2}/|k|^2 = int_eps^inf e^{-t |k|^2} dt.  For a one-loop two-edge
graph the Gaussian loop integral (manuscript lem:c4-gauss, re-derived in gauss_average below) leaves
integrals of the form

    M[a,b,c](p) = iint_{[eps,inf)^2} dt1 dt2  t1^a t2^b s^{-c} exp(-t1 t2 |p|^2 / s),   s = t1 + t2,

whose eps -> 0 expansion (eps^{-1}, log eps, eps^0; the o(1) remainder dropped) is computed EXACTLY
with sympy: t1 = s u, t2 = s (1-u), dt1 dt2 = s ds du, region s >= eps/min(u, 1-u);
the s-integral is an incomplete gamma function of integer order, expanded at small argument,
and the u-integrals of polynomials times logarithms are elementary.

Symbols: p2 = |p|^2 (positive), eps, LE = log(eps) (eps measured in the unit of length ell = 1),
EulerGamma, log(2), log(3).  Results are sympy expressions.
"""
import sympy as sp

p2, eps, LE, b2 = sp.symbols('p2 eps LE beta_2', positive=True)
u = sp.symbols('u', positive=True)
g_E = sp.EulerGamma


def _inner_expansion(n, w, m):
    """E_n(b, w) = int_b^inf s^{-n} e^{-w s} ds with b = eps/m, expanded in eps up to O(eps^0).

    n <= 0: Gamma(1-n) w^{n-1}  (the region [0,b] contributes O(eps^{1-n})).
    n = 1:  -EulerGamma - log(w b)
    n = 2:  1/b + w (EulerGamma + log(w b) - 1)
    n = 3:  1/(2 b^2) - w/b + (w^2/2) (-EulerGamma - log(w b) + 3/2)
    These follow from Gamma(1-n, z) at small z; they are verified numerically in check_masters().
    """
    b = eps / m
    logwb = LE + sp.log(w) - sp.log(m)   # log(w b) = log eps + log w - log m
    if n <= 0:
        return sp.gamma(1 - n) * w**(n - 1)
    if n == 1:
        return -g_E - logwb
    if n == 2:
        return 1 / b + w * (g_E + logwb - 1)
    if n == 3:
        return 1 / (2 * b**2) - w / b + w**2 / 2 * (-g_E - logwb + sp.Rational(3, 2))
    raise ValueError('n > 3 not needed')


def M(a, b, c):
    """Expansion of M[a,b,c](p) in eps: returns a sympy expression in eps, LE, p2 (terms vanishing
    as eps -> 0 dropped)."""
    n = c - a - b - 1
    w = u * (1 - u) * p2
    total = 0
    # sector u <= 1/2 : m = u ;  sector u >= 1/2 : m = 1 - u
    for (m, lo, hi) in ((u, 0, sp.Rational(1, 2)), (1 - u, sp.Rational(1, 2), 1)):
        integrand = u**a * (1 - u)**b * _inner_expansion(n, w, m)
        integrand = sp.expand(sp.expand_log(integrand, force=True))
        total += sp.integrate(integrand, (u, lo, hi))
    total = sp.expand(sp.expand_log(sp.simplify(total), force=True))
    # drop terms that vanish as eps -> 0 (none should be generated by the expansions above)
    return total


def one_edge():
    """int_eps^inf dt / (16 pi^2 t^2) = 1/(16 pi^2 eps): the single-propagator tadpole
    int d^4k/(2pi)^4 e^{-eps k^2}/k^2."""
    return 1 / (16 * sp.pi**2 * eps)


def gauss_average(numerator, lvec, pvec, t1, t2):
    """int d^4l/(2pi)^4 e^{-t1 l^2 - t2 (l-p)^2} numerator(l), numerator a polynomial of degree <= 2
    in the components of l (sympy symbols lvec), p = pvec (sympy symbols).  Completing the square,
    l = l' + (t2/s) p, the Gaussian in l' has normalisation 1/(16 pi^2 s^2), <l'_m l'_n> = delta_mn/(2s).
    Returns the prefactor-free result: (1/(16 pi^2 s^2)) e^{-t1 t2 p^2/s} [ ... ]; we return only
    the bracket [...] as a polynomial in t1, t2, s and the p-components (the exponential and the
    1/(16 pi^2 s^2) are handled by the caller through M[a,b,c])."""
    s = t1 + t2
    shift = {lv: sp.Symbol('lp_%d' % i) + t2 / s * pv for i, (lv, pv) in enumerate(zip(lvec, pvec))}
    lp = [sp.Symbol('lp_%d' % i) for i in range(len(lvec))]
    expr = sp.expand(numerator.subs(shift, simultaneous=True))
    poly = sp.Poly(expr, *lp)
    out = 0
    for monom, coeff in poly.terms():
        deg = sum(monom)
        if deg == 0:
            out += coeff
        elif deg == 2:
            idx = [i for i, e in enumerate(monom) for _ in range(e)]
            if idx[0] == idx[1]:
                out += coeff / (2 * s)
            # mixed l'_m l'_n with m != n averages to zero
        # odd moments vanish
    return sp.expand(out)


def bubble_scalar(numerator_poly_in_t):
    """Given the bracket [...] from gauss_average as a polynomial in t1, t2 (and s = t1 + t2),
    return the exact eps-expansion of iint dt1 dt2 e^{-t1 t2 p2/s}/(16 pi^2 s^2) * bracket.
    The bracket is written in terms of t1, t2 with s eliminated, then expanded monomial by monomial
    into M[a,b,c]."""
    t1, t2 = sp.symbols('t1 t2', positive=True)
    expr = sp.expand(numerator_poly_in_t)
    # collect monomials t1^a t2^b s^{-c}: rewrite negative powers of s as symbol sinv
    sinv = sp.Symbol('sinv', positive=True)
    expr = sp.expand(expr.subs(sp.Symbol('s', positive=True), 1 / sinv))
    poly = sp.Poly(expr, t1, t2, sinv)
    total = 0
    for (a, b, c), coeff in poly.terms():
        total += coeff * M(a, b, c + 2)   # the 1/(16 pi^2 s^2) brings s^{-2}
    return sp.expand(total / (16 * sp.pi**2))


def check_masters(verbose=True):
    """Numerical confirmation of M[a,b,c] against direct 2d quadrature at small eps (mpmath)."""
    import mpmath as mp
    mp.mp.dps = 30
    results = {}
    for (a, b, c) in [(0, 0, 2), (0, 0, 3), (1, 1, 4), (0, 2, 4), (1, 0, 3)]:
        expr = M(a, b, c)
        for e_val in [mp.mpf('1e-3'), mp.mpf('1e-4')]:
            pv = mp.mpf('1.7')
            f = lambda t1, t2: t1**a * t2**b * (t1 + t2)**(-c) * mp.exp(-t1 * t2 * pv / (t1 + t2))
            num = mp.quad(f, [e_val, 10 * e_val, 1, mp.inf], [e_val, 10 * e_val, 1, mp.inf])
            pred = sp.N(expr.subs({p2: sp.Float(str(pv), 30), eps: sp.Float(str(e_val), 30),
                                   LE: sp.log(sp.Float(str(e_val), 30))}), 25)
            rel = abs((num - mp.mpf(str(pred))) / num)
            results[(a, b, c, str(e_val))] = (str(num), str(pred), float(rel))
            if verbose:
                print('M[%d,%d,%d] eps=%s  quad=%s  exact=%s  rel.diff=%.2e (expected O(eps log eps))'
                      % (a, b, c, e_val, mp.nstr(num, 15), mp.nstr(mp.mpf(str(pred)), 15), rel))
    return results


if __name__ == '__main__':
    print('M[0,0,2] =', M(0, 0, 2))
    print('M[0,0,3] =', M(0, 0, 3))
    print('M[1,1,4] =', M(1, 1, 4))
    check_masters()
